#include <stdio.h>

int main()
{
    int dividendo; //definizione variabile
    dividendo=20; //assegnazione valore alla variabile dividendo
    //espressioni con variabile:
    printf("Quoziente: %d\n", dividendo / 7);
    printf("Resto: %d\n", dividendo % 7); //% significa modulo e questo è un commento lineare
}